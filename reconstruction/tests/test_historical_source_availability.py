import unittest

from reconstruction.historical_source_availability import _parse_rdb, _recursive_dates


class HistoricalSourceAvailabilityTests(unittest.TestCase):
    def test_rdb_parser_skips_comments_and_type_row(self):
        source = """# generated by NWIS
agency_cd\tsite_no\tbegin_date\tend_date
5s\t15s\t10d\t10d
USGS\t07375430\t2007-10-01\t2026-11-08
"""
        fields, rows = _parse_rdb(source)
        self.assertEqual(fields, ["agency_cd", "site_no", "begin_date", "end_date"])
        self.assertEqual(rows[0]["begin_date"], "2007-10-01")

    def test_nwps_timestamp_summary_keeps_only_parseable_timestamp_fields(self):
        body = {"observed": [{"validTime": "2018-12-28T17:15:00Z"}],
                "forecast": [{"validTime": "2018-12-29T00:00:00-06:00"}],
                "other": "not-a-time"}
        self.assertEqual(_recursive_dates(body), [
            "2018-12-28T17:15:00+00:00", "2018-12-29T06:00:00+00:00",
        ])


if __name__ == "__main__":
    unittest.main()
